def generate_payment_data(n: int = 8000, anomaly_rate: float = 0.035, seed: int = RANDOM_STATE) -> pd.DataFrame:
    rng = np.random.default_rng(seed)

    n_accounts = 800
    account_ids = np.array([f"ACCT{i:05d}" for i in range(1, n_accounts + 1)])
    countries = ["US", "CA", "GB", "DE", "FR", "MX", "JP", "AU"]
    account_home_country = {a: rng.choice(countries, p=[0.55, 0.10, 0.08, 0.06, 0.06, 0.06, 0.05, 0.04]) for a in account_ids}

    merchant_categories = ["Grocery", "Restaurant", "Gas Station", "Electronics", "Travel", "Online Retail", "Utility", "ATM Withdrawal"]
    category_scale = {"Grocery": 60, "Restaurant": 35, "Gas Station": 45, "Electronics": 250,
                       "Travel": 500, "Online Retail": 90, "Utility": 120, "ATM Withdrawal": 150}
    category_risk = {"Grocery": 1, "Restaurant": 1, "Gas Station": 2, "Electronics": 3,
                      "Travel": 3, "Online Retail": 4, "Utility": 1, "ATM Withdrawal": 5}
    category_p = [0.22, 0.18, 0.15, 0.10, 0.07, 0.15, 0.08, 0.05]

    account_id = rng.choice(account_ids, size=n)
    merchant_category = rng.choice(merchant_categories, size=n, p=category_p)
    txn_datetime = pd.Timestamp("2024-01-01") + pd.to_timedelta(rng.integers(0, 90 * 24 * 60, size=n), unit="m")
    base_amount = np.array([rng.lognormal(mean=np.log(category_scale[c]), sigma=0.6) for c in merchant_category])
    card_country = np.array([account_home_country[a] for a in account_id])

    merchant_country = card_country.copy()
    foreign_p = np.where(merchant_category == "Travel", 0.40,
                 np.where(merchant_category == "Online Retail", 0.15, 0.03))
    foreign_mask = rng.random(n) < foreign_p
    merchant_country[foreign_mask] = rng.choice(countries, size=foreign_mask.sum())

    df = pd.DataFrame({
        "transaction_id": [f"PAY{i:08d}" for i in range(1, n + 1)],
        "txn_datetime": txn_datetime,
        "account_id": account_id,
        "merchant_category": merchant_category,
        "merchant_risk_score": [category_risk[c] for c in merchant_category],
        "transaction_amount": base_amount.round(2),
        "card_country": card_country,
        "merchant_country": merchant_country,
    })
    df["transaction_hour"] = df["txn_datetime"].dt.hour
    df["is_synthetic_anomaly"] = 0

    n_anom = int(n * anomaly_rate)
    anomaly_idx = rng.choice(df.index, size=n_anom, replace=False)
    g1, g2, g3 = np.array_split(rng.permutation(anomaly_idx), 3)

    # Pattern 1: amount spike far above the account/merchant's usual scale
    df.loc[g1, "transaction_amount"] *= rng.uniform(10, 40, size=len(g1))
    # Pattern 2: card-present-abroad style mismatch bundled with a larger amount
    df.loc[g2, "merchant_country"] = [
        rng.choice([c for c in countries if c != cc]) for cc in df.loc[g2, "card_country"]
    ]
    df.loc[g2, "transaction_amount"] *= rng.uniform(3, 8, size=len(g2))
    # Pattern 3: velocity burst - several transactions for one account within a tight window
    burst_accounts = rng.choice(account_ids, size=max(1, len(g3) // 5), replace=False)
    burst_start = pd.Timestamp("2024-01-01") + pd.to_timedelta(rng.integers(0, 90 * 24 * 60, size=len(burst_accounts)), unit="m")
    burst_rows = np.array_split(g3, len(burst_accounts)) if len(burst_accounts) else [g3]
    for acct, start, rows in zip(burst_accounts, burst_start, burst_rows):
        offsets = rng.integers(0, 20, size=len(rows))
        df.loc[rows, "account_id"] = acct
        df.loc[rows, "txn_datetime"] = start + pd.to_timedelta(offsets, unit="m")
    df["transaction_hour"] = df["txn_datetime"].dt.hour

    df.loc[anomaly_idx, "is_synthetic_anomaly"] = 1

    # Velocity feature: rolling count of transactions per account in the trailing hour
    df = df.sort_values(["account_id", "txn_datetime"]).reset_index(drop=True)
    df["txn_count_last_1h"] = (
        df.set_index("txn_datetime").groupby("account_id")["transaction_id"]
        .rolling("1h").count().reset_index(level=0, drop=True).values
    )
    df["days_since_start"] = (df["txn_datetime"] - df["txn_datetime"].min()).dt.days

    # Ratio feature analogous to insurance's claim_to_premium_ratio
    account_avg_amount = df.groupby("account_id")["transaction_amount"].transform("mean")
    df["amount_to_account_avg_ratio"] = df["transaction_amount"] / account_avg_amount.replace(0, np.nan)
    df["amount_to_account_avg_ratio"] = df["amount_to_account_avg_ratio"].fillna(1.0)

    logger.info(
        "Generated %d synthetic payment transactions, %d (%.1f%%) true injected anomalies "
        "across 3 patterns (amount spike, cross-border mismatch, velocity burst)",
        len(df), df["is_synthetic_anomaly"].sum(), 100 * df["is_synthetic_anomaly"].mean(),
    )
    return df


