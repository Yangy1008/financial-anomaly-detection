def main() -> int:
    setup_logging(LOG_PATH)
    logger.info("=== Starting framework portability demonstration ===")

    all_comparisons = []

    try:
        claims = load_insurance_data()
        rows, _ = run_scenario("insurance_claims", claims, INSURANCE_CONFIG, "proxy_label", "proxy")
        all_comparisons.extend(rows)
        cross_check_against_original(rows)
    except FileNotFoundError as e:
        logger.error(str(e))
        return 1
    except Exception:
        logger.error("Scenario 1 (insurance_claims) failed")
        logger.debug(traceback.format_exc())

    try:
        payments = generate_payment_data()
        rows, _ = run_scenario("payment_transactions", payments, PAYMENT_CONFIG, "is_synthetic_anomaly", "true")
        all_comparisons.extend(rows)
    except Exception:
        logger.error("Scenario 2 (payment_transactions) failed")
        logger.debug(traceback.format_exc())

    try:
        funds = generate_fund_data()
        rows, _ = run_scenario("fund_operations", funds, FUND_CONFIG, "is_synthetic_anomaly", "true")
        all_comparisons.extend(rows)
    except Exception:
        logger.error("Scenario 3 (fund_operations) failed")
        logger.debug(traceback.format_exc())

    if not all_comparisons:
        logger.error("All scenarios failed; aborting.")
        return 1

    print_section("Cross-scenario comparison")
    comparison_df = pd.DataFrame(all_comparisons)[
        ["scenario", "method", "label_type", "precision", "recall", "f1", "roc_auc",
         "n_flagged", "flagged_rate", "tn", "fp", "fn", "tp"]
    ]
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    comparison_df.to_csv(OUTPUT_DIR / "portability_comparison.csv", index=False)
    logger.info("Saved -> %s\n%s", OUTPUT_DIR / "portability_comparison.csv",
                comparison_df.round(3).to_string(index=False))

    try:
        write_adaptation_notes(comparison_df)
    except Exception:
        logger.error("Failed to write framework_adaptation_notes.txt")
        logger.debug(traceback.format_exc())

    logger.info("=== Framework portability demonstration finished ===")
    return 0


if __name__ == "__main__":
    sys.exit(main())
