# GENERIC DETECTION ENGINE - identical code path for every domain
# ===========================================================================
def minmax_scale_series(s: pd.Series) -> pd.Series:
    lo, hi = s.min(), s.max()
    if hi - lo < 1e-12:
        return pd.Series(0.0, index=s.index)
    return (s - lo) / (hi - lo)


def compute_group_zscore(df: pd.DataFrame, amount_col: str, group_col: str, threshold: float = 3.0):
    """Statistical method: (x - group_mean) / group_std, standardized within
    each `group_col` so scale differences between groups (e.g. Life claims
    vs Mobile claims, or Bonds vs FX notional) don't dominate the score."""
    group_mean = df.groupby(group_col)[amount_col].transform("mean")
    group_std = df.groupby(group_col)[amount_col].transform("std").replace(0, np.nan)
    z = ((df[amount_col] - group_mean) / group_std).fillna(0)
    flag = z.abs() > threshold
    score = (z.abs() / (threshold * 2)).clip(0, 1)
    return z, flag, score


def compute_isolation_forest(df: pd.DataFrame, feature_cols: list, contamination: float = ASSUMED_ANOMALY_RATE):
    """Isolates anomalies by recursive random splits; points needing fewer
    splits to isolate (short average path length) score as more anomalous.
    Which columns go into `feature_cols` is the only thing that changes
    per domain - the algorithm call is identical everywhere."""
    X = df[feature_cols]
    X_scaled = StandardScaler().fit_transform(X)
    model = IsolationForest(n_estimators=200, contamination=contamination, random_state=RANDOM_STATE)
    pred = model.fit_predict(X_scaled)
    raw = -model.score_samples(X_scaled)
    flag = pred == -1
    score = minmax_scale_series(pd.Series(raw, index=df.index))
    return flag, score


def compute_lof(df: pd.DataFrame, feature_cols: list, contamination: float = ASSUMED_ANOMALY_RATE, n_neighbors: int = 20):
    """Compares each point's local neighbor density to its neighbors'
    density; a point in a much sparser neighborhood is flagged. Distance
    based, so features are standardized first."""
    X = df[feature_cols]
    X_scaled = StandardScaler().fit_transform(X)
    model = LocalOutlierFactor(n_neighbors=n_neighbors, contamination=contamination)
    pred = model.fit_predict(X_scaled)
    raw = -model.negative_outlier_factor_
    flag = pred == -1
    score = minmax_scale_series(pd.Series(raw, index=df.index))
    return flag, score


def compute_rule_based(rules: dict, weights: dict):
    """`rules` is {name: boolean Series}; the binary flag is an OR of all
    rules (fires if ANY rule trips), the continuous score is a weighted sum
    (so claims tripping more/heavier rules score higher for the ensemble)."""
    names = list(rules)
    flag = pd.Series(False, index=rules[names[0]].index)
    score = pd.Series(0.0, index=rules[names[0]].index)
    for name in names:
        flag = flag | rules[name]
        score = score + weights.get(name, 0.0) * rules[name].astype(float)
    return flag, score


def evaluate_method(name: str, y_true: pd.Series, y_score: pd.Series, y_pred: pd.Series) -> dict:
    tn, fp, fn, tp = confusion_matrix(y_true, y_pred, labels=[0, 1]).ravel()
    precision = precision_score(y_true, y_pred, zero_division=0)
    recall = recall_score(y_true, y_pred, zero_division=0)
    f1 = f1_score(y_true, y_pred, zero_division=0)
    try:
        roc_auc = roc_auc_score(y_true, y_score)
    except ValueError:
        roc_auc = np.nan
    logger.info(
        "  [%-17s] precision=%.3f recall=%.3f f1=%.3f roc_auc=%.3f flagged=%d (%.1f%%)",
        name, precision, recall, f1, roc_auc, int(y_pred.sum()), 100 * y_pred.mean(),
    )
    return {
        "precision": precision, "recall": recall, "f1": f1, "roc_auc": roc_auc,
        "tn": int(tn), "fp": int(fp), "fn": int(fn), "tp": int(tp),
        "n_flagged": int(y_pred.sum()), "flagged_rate": float(y_pred.mean()),
    }


def run_scenario(name: str, df: pd.DataFrame, config: dict, label_col: str, label_type: str) -> tuple:
    """The single orchestration path every scenario runs through. Nothing
    here is domain-specific - all domain knowledge lives in `config`."""
    print_section(f"Scenario: {name} (label_type={label_type})")

    z, zflag, zscore = compute_group_zscore(
        df, config["amount_col"], config["group_col"], threshold=config.get("z_threshold", 3.0)
    )
    group_stats = df.groupby(config["group_col"])[config["amount_col"]].agg(["mean", "std"]).round(2)
    group_stats["implied_z3_dollar_threshold"] = (
        group_stats["mean"] + config.get("z_threshold", 3.0) * group_stats["std"]
    ).round(2)
    logger.info(
        "Dollar amount implied by |z|=%.0f threshold, per %s (shows the SAME statistical rule "
        "auto-adapts to each domain's scale without hard-coded dollar thresholds):\n%s",
        config.get("z_threshold", 3.0), config["group_col"], group_stats.to_string(),
    )

    iso_flag, iso_score = compute_isolation_forest(df, config["iso_features"])
    lof_flag, lof_score = compute_lof(df, config["lof_features"])
    rules = config["rules"](df)
    rule_flag, rule_score = compute_rule_based(rules, config["rule_weights"])

    for rule_name, mask in rules.items():
        logger.info("  rule '%s' fires on %d rows (%.1f%%)", rule_name, mask.sum(), 100 * mask.mean())

    scored = df.copy()
    scored["zscore"], scored["zscore_flag"], scored["zscore_score"] = z, zflag, zscore
    scored["iso_flag"], scored["iso_score"] = iso_flag, iso_score
    scored["lof_flag"], scored["lof_score"] = lof_flag, lof_score
    scored["rule_flag"], scored["rule_score"] = rule_flag, rule_score
    scored["ensemble_score"] = (
        ENSEMBLE_WEIGHTS["zscore"] * scored["zscore_score"]
        + ENSEMBLE_WEIGHTS["isolation_forest"] * scored["iso_score"]
        + ENSEMBLE_WEIGHTS["lof"] * scored["lof_score"]
        + ENSEMBLE_WEIGHTS["rule_based"] * scored["rule_score"]
    )

    y_true = df[label_col].astype(int)
    method_flags_scores = {
        "zscore": ("zscore_flag", "zscore_score"),
        "isolation_forest": ("iso_flag", "iso_score"),
        "lof": ("lof_flag", "lof_score"),
        "rule_based": ("rule_flag", "rule_score"),
    }
    comparison_rows = []
    for method, (flag_col, score_col) in method_flags_scores.items():
        row = evaluate_method(method, y_true, scored[score_col], scored[flag_col].astype(int))
        row.update({"scenario": name, "method": method, "label_type": label_type})
        comparison_rows.append(row)

    # Ensemble evaluated at the same contamination rate as the individual methods
    ensemble_threshold = scored["ensemble_score"].quantile(1 - ASSUMED_ANOMALY_RATE)
    ensemble_pred = (scored["ensemble_score"] >= ensemble_threshold).astype(int)
    ensemble_row = evaluate_method("ensemble", y_true, scored["ensemble_score"], ensemble_pred)
    ensemble_row.update({"scenario": name, "method": "ensemble", "label_type": label_type})
    comparison_rows.append(ensemble_row)

    top = scored.nlargest(TOP_N_PER_SCENARIO, "ensemble_score").copy()
    top["explanation"] = top.apply(lambda r: config["explain"](r), axis=1)

    n_true_anoms_in_top = int(top[label_col].sum()) if label_col in top.columns else None
    logger.info(
        "Top %d by ensemble score: mean %s=%.2f (dataset mean=%.2f), positive-label rate in top-N=%s",
        TOP_N_PER_SCENARIO, config["amount_col"], top[config["amount_col"]].mean(),
        scored[config["amount_col"]].mean(),
        f"{100 * n_true_anoms_in_top / TOP_N_PER_SCENARIO:.1f}%" if n_true_anoms_in_top is not None else "n/a",
    )

    out_dir = SCENARIO_DIR / name
    out_dir.mkdir(parents=True, exist_ok=True)
    scored.to_parquet(out_dir / f"{name}_scores.parquet", index=False)
    top[config["explain_cols"] + ["ensemble_score", "explanation"]].to_csv(
        out_dir / f"{name}_top_anomalies.csv", index=False
    )
    pd.DataFrame(comparison_rows).to_csv(out_dir / f"{name}_method_comparison.csv", index=False)
    logger.info("Saved scenario outputs -> %s", out_dir)

    return comparison_rows, scored


