def cross_check_against_original(comparison_rows: list) -> None:
    """Sanity check: the generic engine's insurance numbers should match
    03_anomaly_detection.py's bespoke implementation almost exactly, since
    it is the identical math with the identical config and random_state -
    this is the strongest evidence that the generic engine is a faithful
    refactor rather than a coincidentally-similar reimplementation."""
    if not ORIGINAL_COMPARISON_PATH.exists():
        logger.info("No prior 03_anomaly_detection.py output found - skipping cross-check.")
        return
    original = pd.read_csv(ORIGINAL_COMPARISON_PATH)
    name_map = {"Z-score": "zscore", "Isolation Forest": "isolation_forest",
                "Local Outlier Factor": "lof", "Rule-based": "rule_based"}
    original["method"] = original["method"].map(name_map)
    generic = pd.DataFrame(comparison_rows)
    merged = original.merge(generic, on="method", suffixes=("_03", "_generic"))
    merged["f1_match"] = np.isclose(merged["f1_03"], merged["f1_generic"], atol=1e-6)
    logger.info(
        "Cross-check vs 03_anomaly_detection.py output:\n%s",
        merged[["method", "f1_03", "f1_generic", "f1_match"]].to_string(index=False),
    )
    if merged["f1_match"].all():
        logger.info("All F1 scores match exactly - confirms the generic engine reproduces 03's bespoke results.")
    else:
        logger.warning("Some F1 scores differ from 03's output - expected if 01/03 were re-run with different data.")


